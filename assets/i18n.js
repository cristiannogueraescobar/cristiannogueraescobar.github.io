  function saved() {
    // Remember the user's choice across pages and visits. try/catch because
    // localStorage can throw in private mode or with storage disabled.
    try { return localStorage.getItem('plumline_lang'); } catch (e) { return null; }
  }
  function remember(lang) {
    try { localStorage.setItem('plumline_lang', lang); } catch (e) {}
  }

  function pick() {
    // Priority: an explicit ?lang= in the URL (a shared link) wins, then the
    // user's saved choice, then the browser language, then English.
    var url = (location.search.match(/[?&]lang=(\w\w)/) || [])[1];
    var store = saved();
    var nav = (global.navigator && (navigator.language || 'en')).slice(0, 2);
    var lang = url || store || nav || 'en';
    return DICT[lang] ? lang : 'en';
  }

  function apply(lang, page) {
    if (!DICT[lang]) lang = 'en';
    document.documentElement.lang = lang;
    var tables = [DICT[lang].common || {}, (DICT[lang][page] || {})];
    var en = [DICT.en.common || {}, (DICT.en[page] || {})];
    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute('data-i18n');
      var val = tables[0][key] || tables[1][key] || en[0][key] || en[1][key];
      if (val) nodes[i].innerHTML = val;
    }
    // Also translate ARIA labels tagged with data-i18n-aria="key", so things
    // like a drawer Close button follow the language without extra JS.
    var aria = document.querySelectorAll('[data-i18n-aria]');
    for (var k = 0; k < aria.length; k++) {
      var akey = aria[k].getAttribute('data-i18n-aria');
      var aval = tables[0][akey] || tables[1][akey] || en[0][akey] || en[1][akey];
      if (aval) aria[k].setAttribute('aria-label', aval);
    }
  }

  // public: Plumline.i18n.init(page) wires everything, incl. the <select id="lang">
  global.Plumline = global.Plumline || {};
  global.Plumline.i18n = {
    dict: DICT,
    t: function (lang, page, key) {
      lang = DICT[lang] ? lang : 'en';
      return (DICT[lang][page] && DICT[lang][page][key]) ||
             (DICT[lang].common && DICT[lang].common[key]) ||
             (DICT.en[page] && DICT.en[page][key]) || key;
    },
    init: function (page) {
      var lang = pick();
      // If the URL carried an explicit ?lang=, treat it as a deliberate choice
      // and remember it, so navigating to other pages keeps it.
      var urlLang = (location.search.match(/[?&]lang=(\w\w)/) || [])[1];
      if (urlLang && DICT[urlLang]) remember(urlLang);
      apply(lang, page);
      var sel = document.getElementById('lang');
      if (sel) {
        sel.value = lang;
        sel.addEventListener('change', function () {
          apply(sel.value, page);
          remember(sel.value);
          // Preserve any other query parameters (e.g. ?ex=project-selection)
          // and the hash (e.g. #how) instead of overwriting the whole URL.
          try {
            var params = new URLSearchParams(location.search);
            params.set('lang', sel.value);
            history.replaceState(null, '', location.pathname + '?' + params.toString() + location.hash);
          } catch (e) {}
        });
      }
      return lang;
    }
  };
