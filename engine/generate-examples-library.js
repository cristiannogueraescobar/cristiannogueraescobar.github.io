#!/usr/bin/env node
/* generate:examples-library (Checkpoint F6) — generates the data-bearing outputs of the
 * Examples library from the F5 canonical catalogue, so F7 can add examples WITHOUT hand-
 * editing the page. Two deterministic outputs:
 *
 *   assets/examples-library.js : window.PL_LIBRARY = { schemaVersion, locales,
 *                                categories[], examples[] } projected from the F5
 *                                canonical examples via src/shared/examples/f6/library.js
 *                                (now including F5 tags, localized category labels, and
 *                                localized model-type labels sourced from i18n.js).
 *
 *   examples.html (regions)    : the data-bearing regions between LIBRARY-GENERATED
 *                                markers — the no-JS cards, the populated category filter
 *                                options + counts, the total/live counts, and the JSON-LD
 *                                ItemList. The surrounding F6 layout/markup is NOT touched.
 *
 * Discipline (same as generate-examples.js): loads + validates the F5 canonical first;
 * builds everything in memory; deterministic (stable key order, canonical example order);
 * UTF-8 + LF; no timestamps; no absolute paths; never reads dist; never runs Vite; never
 * touches the engine; Windows/Linux + paths with spaces; two runs produce identical bytes.
 * With --check it writes nothing and exits non-zero if any output is stale. Embedded JSON
 * is `</script>`-safe for inlining.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

// Deterministic content version for the generated payload: the first 12 hex chars of the
// SHA-256 of the payload SOURCE bytes. Same payload bytes => same version; any change to
// the payload (new example, or edited metadata on the existing 9) => a new version. No
// timestamp, no randomness. This is what busts the browser cache when F7 regenerates the
// data-bearing assets/examples-library.js, so a stale cached payload can never mismatch
// the regenerated HTML.
function payloadVersion(payloadSource) {
  return crypto.createHash('sha256').update(payloadSource, 'utf8').digest('hex').slice(0, 12);
}

// ---- deterministic JSON ----
function stableStringify(value) {
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) return '[' + value.map(stableStringify).join(',') + ']';
  const keys = Object.keys(value).sort();
  return '{' + keys.map(function (k) { return JSON.stringify(k) + ':' + stableStringify(value[k]); }).join(',') + '}';
}
function scriptSafe(json) {
  return json
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

// HTML escape for text/attribute content in the generated regions.
function esc(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

// ---- localized model-type labels from the EXISTING i18n dictionary ----
// Single translation source: assets/i18n.js keys mt_continuous/mt_integer/mt_binary/
// mt_mixed. We read them via the public t(lang, page, key) API; no second table.
function modelTypeLabels(siteDir) {
  const i18n = require(path.resolve(siteDir, 'assets', 'i18n.js'));
  const t = i18n.Plumline.i18n.t;
  const LOCALES = ['en', 'es', 'pt', 'de', 'fr'];
  const TYPES = ['continuous', 'integer', 'binary', 'mixed'];
  const out = {};
  TYPES.forEach(function (ty) {
    out[ty] = {};
    LOCALES.forEach(function (loc) { out[ty][loc] = t(loc, 'examples', 'mt_' + ty); });
  });
  return out;
}

// ---- library payload (JS asset) ----
function buildPayload(siteDir) {
  const { loadCanonical } = require(path.resolve(siteDir, 'src', 'shared', 'examples', 'f5', 'index.js'));
  const { libraryPayload } = require(path.resolve(siteDir, 'src', 'shared', 'examples', 'f6', 'library.js'));
  // The generator is catalogue-size agnostic (F7 grows 9 -> 60 without editing it): read
  // the real record count from the F1 catalogue module and validate against THAT, instead
  // of hard-coding 9. loadCanonical still fully validates every record; it just doesn't
  // impose a fixed count the generator has no business owning.
  const catPath = path.resolve(siteDir, 'src', 'shared', 'examples', 'catalogue.js');
  delete require.cache[catPath];
  const { CATALOGUE } = require(catPath);
  const { canonical } = loadCanonical(siteDir, { expectCount: CATALOGUE.length });
  return libraryPayload(canonical, { modelTypeLabels: modelTypeLabels(siteDir) });
}

function buildPayloadSource(siteDir) {
  const payload = buildPayload(siteDir);
  const json = scriptSafe(stableStringify(payload));
  return '/* GENERATED by engine/generate-examples-library.js (Checkpoint F6).\n'
    + ' * Public, metadata-only projection of the F5 canonical examples for the\n'
    + ' * Examples library runtime. DO NOT EDIT BY HAND: regenerate from the canonical\n'
    + ' * catalogue. No grids, expected vectors, domains or baselines are exposed here.\n'
    + ' */\n'
    + '(function (root) {\n'
    + '  root.PL_LIBRARY = ' + json + ';\n'
    + '})(typeof window !== \'undefined\' ? window : this);\n';
}

// ---- data-bearing HTML regions ----
const REF = [];
for (var _i = 1; _i <= 60; _i++) REF.push(_i < 10 ? '0' + _i : String(_i));

function pluralKey(base, n) { return n === 1 ? base + 'One' : base; }

function cardHtml(rec, catLabelEn, idx) {
  const en = rec.locales.en;
  const ref = REF[idx] || String(idx + 1);
  const goal = rec.direction === 'max' ? 'maximise' : 'minimise';
  const goalLabel = rec.direction === 'max' ? 'Maximise' : 'Minimise';
  const decKey = pluralKey('libDecisions', rec.decisions);
  const limKey = pluralKey('libLimits', rec.limits);
  const decWord = rec.decisions === 1 ? 'decision' : 'decisions';
  const limWord = rec.limits === 1 ? 'limit' : 'limits';
  return ''
    + '      <article class="lib-card" data-ex-id="' + esc(rec.id) + '"\n'
    + '               data-category="' + esc(rec.category) + '" data-type="' + esc(rec.modelType) + '"\n'
    + '               data-difficulty="' + esc(rec.difficulty) + '" data-goal="' + esc(goal) + '">\n'
    + '        <div class="lib-card-top">\n'
    + '          <span class="lib-ref">' + esc(ref) + '</span>\n'
    + '          <span class="lib-cat" data-cat-label="' + esc(rec.category) + '">' + esc(catLabelEn) + '</span>\n'
    + '        </div>\n'
    + '        <h3 class="lib-title"><a class="lib-title-link" href="' + esc(rec.solverUrl) + '" data-ex-title="' + esc(rec.id) + '">' + esc(en.title) + '</a></h3>\n'
    + '        <p class="lib-q" data-ex-q="' + esc(rec.id) + '">' + esc(en.question) + '</p>\n'
    + '        <dl class="lib-meta">\n'
    + '          <div class="lib-meta-row"><dt data-i18n="libModelType">Model type</dt><dd><span class="lib-mono" data-i18n="mt_' + esc(rec.modelType) + '">' + esc(rec.modelType) + '</span></dd></div>\n'
    + '          <div class="lib-meta-row"><dt data-i18n="libGoal">Goal</dt><dd><span class="lib-mono" data-i18n="goal_' + esc(goal) + '">' + esc(goalLabel) + '</span></dd></div>\n'
    + '          <div class="lib-meta-row"><dt data-i18n="libDifficulty">Difficulty</dt><dd data-i18n="diff_' + esc(rec.difficulty) + '">' + esc(rec.difficulty) + '</dd></div>\n'
    + '        </dl>\n'
    + '        <div class="lib-facts">\n'
    + '          <span class="lib-fact"><span class="lib-fact-n">' + rec.decisions + '</span> <span data-i18n="' + decKey + '">' + decWord + '</span></span>\n'
    + '          <span class="lib-fact-sep" aria-hidden="true">\u00b7</span>\n'
    + '          <span class="lib-fact"><span class="lib-fact-n">' + rec.limits + '</span> <span data-i18n="' + limKey + '">' + limWord + '</span></span>\n'
    + '          <span class="lib-fact-sep" aria-hidden="true">\u00b7</span>\n'
    + '          <span class="lib-fact"><span class="lib-fact-n">' + rec.minutes + '</span> <span data-i18n="libMinutes">min</span></span>\n'
    + '        </div>\n'
    + '        <a class="lib-cta" href="' + esc(rec.solverUrl) + '"><span data-i18n="libOpenSolver">Open in solver</span> <span aria-hidden="true">&rarr;</span></a>\n'
    + '      </article>';
}

function buildCardsRegion(payload) {
  const catLabel = {};
  payload.categories.forEach(function (c) { catLabel[c.id] = c.label.en; });
  const cards = payload.examples.map(function (rec, i) { return cardHtml(rec, catLabel[rec.category] || rec.category, i); });
  return '\n' + cards.join('\n\n') + '\n';
}

function buildCategoryFiltersRegion(payload) {
  const counts = {};
  payload.examples.forEach(function (r) { counts[r.category] = (counts[r.category] || 0) + 1; });
  const lines = payload.categories
    .filter(function (c) { return counts[c.id]; })
    .map(function (c) {
      return '          <label class="lib-facet-opt"><input type="checkbox" data-facet="category" data-value="'
        + esc(c.id) + '"><span class="lib-facet-label" data-cat-label="' + esc(c.id) + '">'
        + esc(c.label.en) + '</span> <span class="lib-facet-count" data-cat-count="' + esc(c.id) + '">'
        + counts[c.id] + '</span></label>';
    });
  return '\n' + lines.join('\n') + '\n          ';
}

function buildJsonLd(siteDir) {
  const { loadAndValidateCatalogue } = require(path.resolve(siteDir, 'src', 'shared', 'examples', 'index.js'));
  const catPath = path.resolve(siteDir, 'src', 'shared', 'examples', 'catalogue.js');
  delete require.cache[catPath];
  const count = require(catPath).CATALOGUE.length;
  const { catalogue, serialize } = loadAndValidateCatalogue(siteDir, { expectCount: count });
  return '\n<script type="application/ld+json">' + serialize.examplesJsonLd(catalogue) + '</script>\n';
}

function replaceRegion(html, startMarker, endMarker, inner) {
  const s = html.indexOf(startMarker);
  const e = html.indexOf(endMarker);
  if (s === -1 || e === -1 || e < s) throw new Error('generate:examples-library: markers not found: ' + startMarker);
  return html.slice(0, s + startMarker.length) + inner + html.slice(e);
}
function replaceInline(html, name, value) {
  const start = '<!--' + name + '-->';
  const end = '<!--/' + name + '-->';
  const s = html.indexOf(start), e = html.indexOf(end);
  if (s === -1 || e === -1 || e < s) throw new Error('generate:examples-library: inline marker not found: ' + name);
  return html.slice(0, s + start.length) + value + html.slice(e);
}

function buildExamplesHtml(siteDir) {
  const payload = buildPayload(siteDir);
  const total = payload.examples.length;
  const version = payloadVersion(buildPayloadSource(siteDir));
  const htmlPath = path.join(siteDir, 'examples.html');
  let html = fs.readFileSync(htmlPath, 'utf8');

  html = replaceRegion(html,
    '<!-- LIBRARY-GENERATED:CARDS START (generated by engine/generate-examples-library.js from the F5 canonical catalogue; do not edit by hand) -->',
    '      <!-- LIBRARY-GENERATED:CARDS END -->',
    buildCardsRegion(payload));

  html = replaceRegion(html,
    '<!-- LIBRARY-GENERATED:CATEGORY-FILTERS START (populated categories + counts, from the F5 canonical catalogue) -->',
    '          <!-- LIBRARY-GENERATED:CATEGORY-FILTERS END -->',
    buildCategoryFiltersRegion(payload));

  html = replaceRegion(html,
    '<!--LIBRARY-GENERATED:JSONLD START-->',
    '<!--LIBRARY-GENERATED:JSONLD END-->',
    buildJsonLd(siteDir));

  // Cache-bust the data-bearing payload script from its content digest. Only the payload
  // <script> is regenerated; core/ui stay stable across F7. Owned by a dedicated marker.
  html = replaceRegion(html,
    '<!--LIBRARY-GENERATED:PAYLOAD-SCRIPT (src + cache-bust version generated by engine/generate-examples-library.js from the payload content digest; do not edit by hand)-->',
    '<!--/LIBRARY-GENERATED:PAYLOAD-SCRIPT-->',
    '<script src="assets/examples-library.js?v=' + version + '"></script>');

  html = replaceInline(html, 'LIBRARY-GENERATED:TOTAL', String(total));
  html = replaceInline(html, 'LIBRARY-GENERATED:COUNT', String(total));

  return html;
}

function run(siteDir, opts) {
  opts = opts || {};
  const outputs = [];

  const jsPath = path.join(siteDir, 'assets', 'examples-library.js');
  const jsNext = buildPayloadSource(siteDir);
  const jsCur = fs.existsSync(jsPath) ? fs.readFileSync(jsPath, 'utf8') : null;
  if (jsCur !== jsNext) outputs.push({ path: 'assets/examples-library.js', abs: jsPath, next: jsNext });

  const htmlPath = path.join(siteDir, 'examples.html');
  const htmlNext = buildExamplesHtml(siteDir);
  const htmlCur = fs.existsSync(htmlPath) ? fs.readFileSync(htmlPath, 'utf8') : null;
  if (htmlCur !== htmlNext) outputs.push({ path: 'examples.html', abs: htmlPath, next: htmlNext });

  const changed = outputs.map(function (o) { return o.path; });
  if (opts.check) return { ok: changed.length === 0, changed: changed };
  outputs.forEach(function (o) {
    const tmp = o.abs + '.tmp-gen';
    fs.writeFileSync(tmp, o.next, { encoding: 'utf8' });
    fs.renameSync(tmp, o.abs);
  });
  return { ok: true, changed: changed };
}

module.exports = {
  run: run,
  payloadVersion: payloadVersion,
  buildPayload: buildPayload,
  buildPayloadSource: buildPayloadSource,
  buildExamplesHtml: buildExamplesHtml,
  modelTypeLabels: modelTypeLabels,
  stableStringify: stableStringify,
  scriptSafe: scriptSafe,
};

if (require.main === module) {
  const siteDir = path.join(__dirname, '..');
  const check = process.argv.indexOf('--check') !== -1;
  const r = run(siteDir, { check: check });
  if (check) {
    if (r.ok) { console.log('generate:examples-library --check: up to date'); process.exit(0); }
    console.error('generate:examples-library --check: STALE (' + r.changed.join(', ') + ')'); process.exit(1);
  } else {
    console.log('generate:examples-library: ' + (r.changed.length ? 'wrote ' + r.changed.join(', ') : 'no changes'));
  }
}
